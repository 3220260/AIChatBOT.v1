// Συνάρτηση για fuzzy matching - βρίσκει την πιο κοντινή ερώτηση
export function findBestMatch(userMessage) {
  const normalizedMessage = userMessage.toLowerCase()
    .normalize("NFD").replace(/[\u0300-\u036f]/g, ""); // Αφαίρεση τόνων
  
  let bestMatch = null;
  let highestScore = 0;

  for (const faq of FAQ_DATABASE) {
    let score = 0;
    
    // Μετράμε πόσες λέξεις-κλειδιά βρίσκονται στο μήνυμα
    for (const keyword of faq.keywords) {
      if (normalizedMessage.includes(keyword)) {
        score += 1;
      }
    }
    
    // Αν βρήκαμε match και είναι καλύτερο από το προηγούμενο
    if (score > highestScore) {
      highestScore = score;
      bestMatch = faq;
    }
  }
  
  // Επιστρέφουμε την απάντηση αν βρήκαμε αρκετά καλό match (τουλάχιστον 1 keyword)
  if (highestScore >= 1) {
    return bestMatch.answer;
  }
  
  return null; // Δεν βρέθηκε match - θα χρησιμοποιηθεί το Gemini
}
